func TestEveryAboutRuleHasAnExample(t *testing.T) {
	hit := map[int]bool{}
	for _, e := range aboutExamples {
		r, ok := ruleOf(e.ua)
		if !ok {
			t.Errorf("%q: no about rule takes it", e.ua)
			continue
		}
		for i := range aboutRules {
			if aboutRules[i].text == r.text && aboutRules[i].re == r.re {
				hit[i] = true
			}
		}
		if got := kindOf(e.ua); got != e.kind {
			t.Errorf("%q: kind %q, want %q (about: %q)", e.ua, got, e.kind, r.label)
		}
	}
	for i, r := range aboutRules {
		if !hit[i] {
			t.Errorf("rule %d %q has no example, or an earlier rule takes all of them", i, r.re)
		}
	}
}
